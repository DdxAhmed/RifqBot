import { helpMenuKeyboard } from '../keyboards/main.keyboard.js';

export function formatHelpMessage() {
  return '❓ **دليل مساعدة رِفْق** 🌿\n\n' +
    'رِفْق مصمم لمساعدتك على إنجاز مهامك دون أي ضغط أو تشتت:\n\n' +
    '📅 **خطتي اليوم:** ملخص شامل ليومك (تذكيراتك، دروسك، أهدافك، أذكارك).\n' +
    '⏰ **تذكيراتي:** إنشاء تذكيرات ذكية متكررة أو لمرة واحدة مع التنبيهات.\n' +
    '📚 **كورساتي:** تتبع فصول ودروس دوراتك وحساب وتيرة الإنجاز.\n' +
    '🎯 **أهدافي:** وضع أهداف يومية محددة ومتابعة إنجازها.\n' +
    '📝 **ملاحظاتي:** تسجيل سريع للأفكار والملاحظات مع إمكانية البحث.\n' +
    '🤲 **أذكاري:** جلسات تفاعلية لورد الصباح والمساء بعداد ذكي.\n' +
    '📊 **تقدمي:** إحصائيات دقيقة وسلسلة إنجازك المستمرة.\n\n' +
    '💡 **نصيحة:** لست بحاجة لحفظ أي أوامر! يمكنك التنقل بين جميع الميزات والخدمات بسهولة عبر أزرار القائمة أسفل كل شاشة.';
}

export function registerHelpCommand(bot) {
  bot.command(['help', 'menu'], async (ctx) => {
    ctx.userSession?.clear();
    const text = formatHelpMessage();
    return ctx.reply(text, { parse_mode: 'Markdown', ...helpMenuKeyboard() });
  });
}
